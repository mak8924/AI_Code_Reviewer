# 1. استيراد مكتبة Streamlit للوصول إلى مفاتيح الأمان والبيانات السرية المخزنة
import streamlit as st

# 2. استيراد مكتبة Google Generative AI المخصصة للتواصل مع نماذج الذكاء الاصطناعي Gemini
import google.generativeai as genai

# 3. جلب مفتاح الـ API الخاص بنماذج جوجل والمخزن بأمان داخل ملف secrets.toml الخاص بـ Streamlit
api_key = st.secrets["GEMINI_API_KEY"]

# 4. إعداد وتكوين مكتبة Google Generative AI باستخدام مفتاح الـ API المستخرج
genai.configure(api_key=api_key)


# 5. دالة فرعية لبناء النص التوجيهي (Prompt) بشكل مرن يتكيف مع كافة مستويات الخطورة
def build_dynamic_prompt(code_text, risk_status="Low"):
    # 6. صياغة النص التوجيهي الذكي ليحلل الكود سواء كان سليماً أو يحتوي ثغرات
    prompt = f"""
    أنت خبير فحص جودة وأمن برمجيات. قم بتحليل الكود البرمجي التالي (تقييم المخاطر الهيكلية المحسوبة محلياً: {risk_status}):
    
    ```python
    {code_text}
    ```
    
    المطلوب منك بالتحديد:
    1. تقييم جودة وأمان الكود، وتحديد أي ثغرات أو أخطاء برمجية إن وُجدت، أو التأكيد على سلامته ونظافته إن كان خالياً منها.
    2. تحديد درجة الخطورة الأمنية الفعلية (High, Medium, Low).
    3. تقديم الكود المصحح أو المحسن بالكامل مع كتابة جميع التعليقات الشارحة داخل الكود باللغة العربية.
    4. تقديم شرح سريع ومختصر جداً للتعديلات أو أفضل الممارسات المقترحة.
    
    قواعد صارمة للغة والتنسيق:
    - يجب أن تكون جميع الشروحات والنصوص والتعليقات المكتوبة داخل الكود وخارجه باللغة العربية فقط.
    - يُسمح بترك الأكواد البرمجية والمصطلحات التقنية الأساسية فقط باللغة الإنجليزية.
    """
    # 7. إرجاع النص التوجيهي المكتمل للجهات المستدعية
    return prompt


# 8. الدالة الرئيسية لتحليل الكود والتي تُستدعى من ملف app.py مباشرة
def analyze_code(code_text, risk_status="Low"):
    # 9. بناء النص التوجيهي المخصص عبر الدالة الفرعية
    prompt = build_dynamic_prompt(code_text, risk_status)

    # 10. قائمة بالنماذج المتاحة للتجربة بالتتابع في حال انشغال أحدها أو استهلاك حصته
    candidate_models = ["gemini-2.0-flash", "gemini-1.5-flash", "gemini-1.5-pro"]

    # 11. التكرار على جميع النماذج لتجربة الاستجابة
    for model_name in candidate_models:
        # 12. بداية كتلة تجربة التنفيذ للنموذج الحالي
        try:
            # 13. إنشاء كائن النموذج باستخدام الاسم الحالي
            model = genai.GenerativeModel(model_name)

            # 14. إرسال الطلب واستقبال النتيجة من النموذج
            response = model.generate_content(prompt)

            # 15. إرجاع النتيجة النصية فور النجاح
            return response.text
        # 16. التقاط الخطأ والسيطرة عليه في حال تعذر النموذج الحالي
        except Exception:
            # 17. الانتقال للنموذج التالي في القائمة
            continue

    # 18. إرجاع نص توضيحي في حال استنفاد جميع النماذج دون إيقاف الواجهة
    return "⚠️ تم تجاوز الحد المسموح لطلبات Gemini API مؤقتاً. تم الاعتماد على تقييم النموذج المحلي."


# 19. دالة تحليل الكود بنظام البث المباشر المعتمدة في app.py
def analyze_code_with_gemini_stream(code_text, risk_status="Low"):
    # 20. بناء النص التوجيهي المخصص عبر الدالة الفرعية
    prompt = build_dynamic_prompt(code_text, risk_status)

    # 21. قائمة النماذج المتاحة لتجربتها بالترتيب
    candidate_models = ["gemini-2.0-flash", "gemini-1.5-flash", "gemini-1.5-pro"]

    # 22. التكرار على النماذج لإيجاد النموذج الشغال
    for model_name in candidate_models:
        # 23. بداية كتلة التجربة للبث المباشر
        try:
            # 24. إنشاء كائن النموذج
            model = genai.GenerativeModel(model_name)

            # 25. طلب التوليد بنظام البث المباشر
            response = model.generate_content(prompt, stream=True)

            # 26. التكرار على الأجزاء الواصلة وإرجاعها
            for chunk in response:
                # 27. التأكد من وجود نص في الجزء الحالي
                if chunk.text:
                    # 28. إرجاع الجزء النصي تدريجياً
                    yield chunk.text

            # 29. الخروج من الدالة فور اكتمال البث بنجاح
            return
        # 30. التقاط الخطأ وتجربة النموذج التالي
        except Exception:
            # 31. الانتقال للنموذج التالي
            continue

    # 32. إرجاع رسالة تنبيهية في حال تعذر البث المباشر من كل النماذج
    yield "⚠️ تم تجاوز الحد المسموح لطلبات Gemini API مؤقتاً. تم الاعتماد على تقييم النموذج المحلي."