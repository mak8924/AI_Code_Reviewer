# 1. استيراد مكتبة Streamlit للوصول إلى مفاتيح الأمان والبيانات السرية المخزنة
import streamlit as st

# 2. استيراد مكتبة Google Generative AI المخصصة للتواصل مع نماذج الذكاء الاصطناعي Gemini
import google.generativeai as genai

# 3. جلب مفتاح الـ API الخاص بنماذج جوجل والمخزن بأمان داخل ملف secrets.toml الخاص بـ Streamlit
api_key = st.secrets["GEMINI_API_KEY"]

# 4. إعداد وتكوين مكتبة Google Generative AI باستخدام مفتاح الـ API المستخرج
genai.configure(api_key=api_key)

# 5. تعريف الدالة الأولى لحساب وتحليل الكود وإرجاع النتيجة بالكامل دفعة واحدة
def analyze_code(code_text):
    # 6. إنشاء كائن النموذج المحدد من جوجل لاستخدامه في عملية التحليل البرمجي
    model = genai.GenerativeModel('gemma-4-26b-a4b-it')
    
    # 7. صياغة النص التوجيهي (Prompt) مع إضافة شروط التحدث باللغة العربية وضبط المصطلحات والتعليقات
    prompt = f"""
    أنت خبير أمن برمجيات. قم بتحليل الكود التالي الذي يحتوي على أخطاء أو مخاطر:
    
    ```
    {code_text}
    ```
    
    المطلوب منك بالتحديد:
    1. تحديد الثغرات البرمجية/الأمنية الموجودة فيه.
    2. إعطاء درجة الخطورة (High, Medium, Low).
    3. تقديم الكود المصحح والمعدل بالكامل مع كتابة جميع التعليقات الشارحة داخل الكود باللغة العربية.
    4. تقديم شرح سريع ومختصر جداً للتعديلات التي قمت بها.
    
    قواعد صارمة للغة والتنسيق:
    - يجب أن تكون جميع الشروحات والنصوص والتعليقات المكتوبة داخل الكود وخارجه باللغة العربية فقط.
    - يُسمح بترك الأكواد البرمجية والمصطلحات التقنية الأساسية فقط باللغة الإنجليزية.
    """
    
    # 8. إرسال الطلب والنص التوجيهي للنموذج واستقبال الاستجابة الكاملة
    response = model.generate_content(prompt)
    
    # 9. إرجاع النص الناتج من رد الذكاء الاصطناعي للجهة المستدعية
    return response.text

# 10. تعريف الدالة الثانية لإجراء التحليل وإرسال النتيجة كبث مباشر تدريجي (Streaming)
def analyze_code_with_gemini_stream(code_text):
    # 11. إنشاء كائن النموذج المعتمد للتحليل بالبث المباشر
    model = genai.GenerativeModel('gemma-4-26b-a4b-it')
    
    # 12. صياغة النص التوجيهي وتضمين القواعد الصارمة للغة العربية والشروحات والتعليقات
    prompt = f"""
    أنت خبير أمن برمجيات. قم بتحليل الكود التالي الذي يحتوي على أخطاء أو مخاطر:
    
    ```
    {code_text}
    ```
    
    المطلوب منك بالتحديد:
    1. تحديد الثغرات البرمجية/الأمنية الموجودة فيه.
    2. إعطاء درجة الخطورة (High, Medium, Low).
    3. تقديم الكود المصحح والمعدل بالكامل مع كتابة جميع التعليقات الشارحة داخل الكود باللغة العربية.
    4. تقديم شرح سريع ومختصر جداً للتعديلات التي قمت بها.
    
    قواعد صارمة للغة والتنسيق:
    - يجب أن تكون جميع الشروحات والنصوص والتعليقات المكتوبة داخل الكود وخارجه باللغة العربية فقط.
    - يُسمح بترك الأكواد البرمجية والمصطلحات التقنية الأساسية فقط باللغة الإنجليزية.
    """
    
    # 13. إرسال طلب التوليد بنظام البث المباشر بتفعيل المعامل stream=True
    response = model.generate_content(prompt, stream=True)
    
    # 14. التكرار على الأجزاء النصية الواصلة بشكل متتابع من خوادم الذكاء الاصطناعي
    for chunk in response:
        # 15. التحقق من وجود محتوى نصي في الجزء الحالي المجلوب
        if chunk.text:
            # 16. إرجاع الجزء النصي فور وصوله باستخدام المولد yield للتعامل مع البث المباشر
            yield chunk.text